"""Build editable faculty slides; optional measured figures never trigger experiments."""
from pathlib import Path
import argparse
import json

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.util import Inches, Pt


def add_bullets(slide, bullets, left, top, width, height, font_size, space_after, color):
    textbox = slide.shapes.add_textbox(left, top, width, height)
    frame = textbox.text_frame
    frame.word_wrap = True
    for j, bullet in enumerate(bullets):
        p = frame.paragraphs[0] if j == 0 else frame.add_paragraph()
        p.text = f"• {bullet}" if not bullet.startswith("[") else bullet
        p.font.size = Pt(font_size)
        p.font.color.rgb = color
        p.space_after = Pt(space_after)
    return frame


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--report', type=Path, help='Completed build-report output directory')
    parser.add_argument('--eeg-plot', type=Path, default=Path('outputs/eeg_example/eeg_example.png'),
                        help='Illustrative EEG figure generated by plot-eeg')
    parser.add_argument('--out', type=Path, default=Path('slides/presentation_draft.pptx'))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    content = json.loads((root / 'slides/content.json').read_text(encoding='utf-8'))
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    navy, teal = RGBColor(18, 35, 58), RGBColor(0, 120, 125)
    for i, entry in enumerate(content, 1):
        slide = prs.slides.add_slide(prs.slide_layouts[6])
        bg = slide.background.fill
        bg.solid()
        bg.fore_color.rgb = RGBColor(248, 250, 252)
        title = slide.shapes.add_textbox(Inches(.65), Inches(.35), Inches(12.0), Inches(.8))
        paragraph = title.text_frame.paragraphs[0]
        paragraph.text = entry['title']
        paragraph.font.size, paragraph.font.bold = Pt(28), True
        paragraph.font.color.rgb = navy

        has_report = args.report is not None
        if i == 7 and has_report and args.eeg_plot.is_file():
            add_bullets(slide, entry['bullets'], Inches(.65), Inches(1.35), Inches(5.6), Inches(5.3),
                        font_size=18, space_after=14, color=navy)
            slide.shapes.add_picture(str(args.eeg_plot), Inches(6.4), Inches(1.4), width=Inches(6.4))
        elif i == 10 and has_report:
            acc_fig = args.report / 'accuracy.png'
            cm_fig = args.report / 'confusion_matrices.png'
            if not acc_fig.is_file() or not cm_fig.is_file():
                raise FileNotFoundError(f'Missing report figures in {args.report}')
            add_bullets(slide, entry['bullets'], Inches(.65), Inches(1.2), Inches(12.0), Inches(2.15),
                        font_size=16, space_after=6, color=navy)
            slide.shapes.add_picture(str(acc_fig), Inches(.65), Inches(3.55), width=Inches(5.7))
            slide.shapes.add_picture(str(cm_fig), Inches(6.55), Inches(3.75), width=Inches(6.2))
        elif i == 11 and has_report:
            svd_fig = args.report / 'svd_diagnostics.png'
            if not svd_fig.is_file():
                raise FileNotFoundError(svd_fig)
            add_bullets(slide, entry['bullets'], Inches(.65), Inches(1.2), Inches(12.0), Inches(2.65),
                        font_size=15, space_after=6, color=navy)
            slide.shapes.add_picture(str(svd_fig), Inches(2.1), Inches(4.05), width=Inches(9.1))
        else:
            font_size = 18 if i > 18 else (26 if i == 1 else 21)
            space_after = 14 if i > 18 else 16
            add_bullets(slide, entry['bullets'], Inches(.8), Inches(1.45), Inches(11.7), Inches(5.2),
                        font_size=font_size, space_after=space_after, color=navy)

        footer = slide.shapes.add_textbox(Inches(.7), Inches(7.02), Inches(12), Inches(.3))
        p = footer.text_frame.paragraphs[0]
        if has_report:
            p.text = f'{i:02d} | SVD + RBF SVM | Exploratory follow-up (N = 105 eligible participants)'
        else:
            p.text = f'{i:02d} | SVD + RBF SVM | DRAFT — empirical conclusions require local results'
        p.font.size = Pt(11)
        p.font.color.rgb = teal
        slide.notes_slide.notes_text_frame.text = entry['notes'] + f"\nSuggested time: {entry['minutes']} minutes."
    if args.out.exists():
        raise FileExistsError(f'Refusing to overwrite {args.out}')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    prs.save(args.out)
    print(f'Saved {len(content)} slides ({sum(s["minutes"] for s in content):g} scheduled minutes): {args.out}')


if __name__ == '__main__':
    main()
